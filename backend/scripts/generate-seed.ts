/**
 * Generates SQL seed files from the frontend's mock data:
 *   seed/events.sql – the public events only (safe for production)
 *   seed/demo.sql   – events + demo members, shifts, hosts, notes, reviews
 *
 * Run from backend/: npm run db:seed:generate
 * Every demo account gets the password "esn-demo-2026" (never use in production).
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { mockEvents } from "@/mocks/events";
import { mockEventTasks } from "@/mocks/eventTasks";
import { mockEventTeamInfo } from "@/mocks/eventTeamInfo";
import { mockMembers } from "@/mocks/members";
import { mockReviewNotes } from "@/mocks/reviewNotes";
import { EsnEventSchema } from "@/types/event";
import { EventTaskSchema, EventTeamInfoSchema, ReviewNoteSchema } from "@/types/team";

import { hashPassword } from "../src/lib/password";

export const DEMO_PASSWORD = "esn-demo-2026";
const SEED_TIME = "2026-11-01T09:00:00.000Z";

const outDir = join(dirname(fileURLToPath(import.meta.url)), "..", "seed");

function q(value: string | number | boolean | null | undefined): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "boolean") return value ? "1" : "0";
  if (typeof value === "number") return String(value);
  return `'${value.replace(/'/g, "''")}'`;
}

const insert = (table: string, row: Record<string, string | number | boolean | null | undefined>) =>
  `INSERT INTO ${table} (${Object.keys(row).join(", ")}) VALUES (${Object.values(row).map(q).join(", ")});`;

// Main events first, so sub-events can point at them.
const events = mockEvents
  .map((e) => EsnEventSchema.parse(e))
  .sort((a, b) => Number(Boolean(a.parentSlug)) - Number(Boolean(b.parentSlug)));
const eventSql = events.map((e) =>
  insert("events", {
    id: e.id,
    slug: e.slug,
    title: e.title,
    summary: e.summary,
    description: e.description,
    category: e.category,
    status: e.status,
    start_date: e.startDate,
    end_date: e.endDate,
    start_time: e.startTime,
    end_time: e.endTime,
    location: e.location,
    price_info: e.priceInfo,
    registration_url: e.registrationUrl,
    image_url: e.imageUrl,
    tags: JSON.stringify(e.tags),
    parent_slug: e.parentSlug,
    created_at: SEED_TIME,
    updated_at: SEED_TIME,
  }),
);

const slugs = new Set(events.map((e) => e.slug));
const memberIds = new Set(mockMembers.map((m) => m.id));

const userSql: string[] = [];
for (const m of mockMembers) {
  userSql.push(
    insert("users", {
      id: m.id,
      name: m.name,
      email: m.email?.toLowerCase(),
      role: m.role,
      status: m.status ?? "active",
      team: m.team,
      password_hash: await hashPassword(DEMO_PASSWORD),
      created_at: m.createdAt ?? SEED_TIME,
      updated_at: SEED_TIME,
    }),
  );
}

const teamSql: string[] = [];
for (const raw of mockEventTeamInfo) {
  const info = EventTeamInfoSchema.parse(raw);
  if (!slugs.has(info.eventSlug)) continue;
  teamSql.push(
    insert("event_team_info", {
      event_slug: info.eventSlug,
      notes: info.notes,
      links: JSON.stringify(info.links),
      updated_at: info.updatedAt,
      updated_by: info.updatedBy,
    }),
  );
  for (const hostId of info.hostIds.filter((id) => memberIds.has(id))) {
    teamSql.push(insert("event_hosts", { event_slug: info.eventSlug, user_id: hostId }));
  }
}

for (const raw of mockEventTasks) {
  const t = EventTaskSchema.parse(raw);
  if (!slugs.has(t.eventSlug)) continue;
  teamSql.push(
    insert("tasks", {
      id: t.id,
      event_slug: t.eventSlug,
      kind: t.kind,
      title: t.title,
      description: t.description,
      date: t.date,
      start_time: t.startTime,
      end_time: t.endTime,
      location: t.location,
      people_needed: t.peopleNeeded,
      done: t.done,
      created_by: t.createdBy && memberIds.has(t.createdBy) ? t.createdBy : null,
      created_at: t.createdAt ?? SEED_TIME,
      updated_at: t.updatedAt ?? SEED_TIME,
    }),
  );
  for (const id of t.assigneeIds.filter((a) => memberIds.has(a))) {
    teamSql.push(insert("task_assignees", { task_id: t.id, user_id: id, assigned_at: SEED_TIME }));
  }
}

for (const raw of mockReviewNotes) {
  const n = ReviewNoteSchema.parse(raw);
  if (!slugs.has(n.eventSlug)) continue;
  teamSql.push(
    insert("review_notes", {
      id: n.id,
      event_slug: n.eventSlug,
      kind: n.kind,
      text: n.text,
      author_id: memberIds.has(n.authorId) ? n.authorId : null,
      created_at: n.createdAt,
    }),
  );
}

const header = (what: string) =>
  `-- Generated by scripts/generate-seed.ts from src/mocks. ${what}\n-- Do not edit by hand.\n`;

writeFileSync(
  join(outDir, "events.sql"),
  `${header("Public events only.")}${eventSql.join("\n")}\n`,
);
writeFileSync(
  join(outDir, "demo.sql"),
  `${header(`Demo data. Every account's password: ${DEMO_PASSWORD}. Never load into production.`)}` +
    [...userSql, ...eventSql, ...teamSql].join("\n") +
    "\n",
);
console.log(
  `Wrote seed/events.sql (${eventSql.length} events) and seed/demo.sql (${userSql.length} members, ${teamSql.length} team rows).`,
);
